export function isTwoPartyConsentState(code: string | null): boolean {
  if (!code) return false;
  return TWO_PARTY_CONSENT_STATES.has(code.toUpperCase());
}

export function consentScriptFor(
  customerName: string | null,
  repName: string | null,
  companyName: string | null,
): string {
  const customer = customerName?.split(" ")[0] || "there";
  const rep = repName?.split(" ")[0] || "I";
  const company = companyName || "our team";
  return `Hi ${customer}, ${rep} from ${company}. I'm using AI tools during today's visit to help capture every detail accurately — is that ok with you?`;
}
